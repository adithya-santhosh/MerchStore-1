"use client";

import React, { createContext, useContext, useState, useEffect } from "react";
import { Cart, CartItem } from "@/types/cart";
import { useAuth } from "./useAuth";
import { getCookie } from "@/utils/cookie";

const API_URL = process.env.NEXT_PUBLIC_API_URL || "http://127.0.0.1:5000";

interface SystemSettings {
  tax_rate: number;
  shipping_limit: number;
  shipping_cost: number;
}

interface CartContextType {
  cart: Cart | null;
  itemsCount: number;
  subtotal: number;
  loading: boolean;
  settings: SystemSettings;
  isSidebarOpen: boolean;
  setSidebarOpen: (open: boolean) => void;
  addToCart: (productId: number, quantity?: number) => Promise<void>;
  updateQuantity: (productId: number, quantity: number) => Promise<void>;
  removeFromCart: (productId: number) => Promise<void>;
  clearCart: () => void;
  refreshSettings: () => Promise<void>;
  validateCouponOnServer: (code: string, orderAmount: number) => Promise<{ code: string; type: string; value: number }>;
}

const CartContext = createContext<CartContextType | undefined>(undefined);

export const CartProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [cart, setCart] = useState<Cart | null>(null);
  const [sessionToken, setSessionToken] = useState<string | null>(null);
  const [isTokenLoaded, setIsTokenLoaded] = useState<boolean>(false);
  const [loading, setLoading] = useState<boolean>(true);
  const [isSidebarOpen, setSidebarOpen] = useState<boolean>(false);
  const { user } = useAuth();
  const [settings, setSettings] = useState<SystemSettings>({
    tax_rate: 0.18,
    shipping_limit: 499,
    shipping_cost: 99
  });

  // Initialize session token from localStorage
  useEffect(() => {
    if (typeof window !== "undefined") {
      const savedToken = localStorage.getItem("sessionToken");
      if (savedToken) {
        setSessionToken(savedToken);
      }
      setIsTokenLoaded(true);
    }
  }, []);

  const fetchSettings = async () => {
    try {
      const res = await fetch(`${API_URL}/api/settings`, { cache: "no-store" });
      if (res.ok) {
        const data = await res.json();
        setSettings(data);
      }
    } catch (err) {
      console.error("Failed to fetch settings:", err);
    }
  };

  // Fetch settings on mount
  useEffect(() => {
    fetchSettings();
  }, []);

  // Fetch cart once token state is loaded from localStorage
  useEffect(() => {
    if (!isTokenLoaded) return;

    const fetchCart = async () => {
      try {
        let url = `${API_URL}/api/cart`;
        if (!user && sessionToken) {
          url += `?sessionToken=${sessionToken}`;
        }
        
        const tokenCookie = getCookie("token");
        const headers: HeadersInit = {};
        if (tokenCookie) {
          headers["Authorization"] = `Bearer ${tokenCookie}`;
        }
        if (!user && sessionToken) {
          headers["x-session-token"] = sessionToken;
        }

        const response = await fetch(url, {
          cache: "no-store",
          headers
        });

        if (response.ok) {
          const data: Cart = await response.json();
          setCart(data);
          
          // Store token if generated by the backend and not logged in
          if (!user && !sessionToken && data.sessionToken) {
            localStorage.setItem("sessionToken", data.sessionToken);
            setSessionToken(data.sessionToken);
          }
        }
      } catch (error) {
        console.error("Failed to load cart:", error);
      } finally {
        setLoading(false);
      }
    };

    fetchCart();
  }, [sessionToken, isTokenLoaded, user]);

  const addToCart = async (productId: number, quantity: number = 1) => {
    let token = sessionToken;
    if (!user && !token) {
      token = typeof window !== "undefined" ? window.crypto?.randomUUID() || Math.random().toString(36).substring(2) : "";
      if (typeof window !== "undefined" && token) {
        localStorage.setItem("sessionToken", token);
        setSessionToken(token);
      }
    }

    try {
      const tokenCookie = getCookie("token");
      const headers: HeadersInit = {
        "Content-Type": "application/json"
      };
      if (tokenCookie) {
        headers["Authorization"] = `Bearer ${tokenCookie}`;
      }
      if (!user && token) {
        headers["x-session-token"] = token;
      }

      const response = await fetch(`${API_URL}/api/cart/items`, {
        method: "POST",
        headers,
        body: JSON.stringify({ productId, quantity }),
      });

      if (response.ok) {
        const updatedCart = await response.json();
        setCart(updatedCart);
        // Automatically open the sidebar to show the item was added
        setSidebarOpen(true);
      } else {
        console.error("Failed to add item to cart");
      }
    } catch (error) {
      console.error("Error adding item to cart:", error);
    }
  };

  const updateQuantity = async (productId: number, quantity: number) => {
    const token = sessionToken || (typeof window !== "undefined" ? localStorage.getItem("sessionToken") : null);
    if (!user && !token) return;
    try {
      const tokenCookie = getCookie("token");
      const headers: HeadersInit = {
        "Content-Type": "application/json"
      };
      if (tokenCookie) {
        headers["Authorization"] = `Bearer ${tokenCookie}`;
      }
      if (!user && token) {
        headers["x-session-token"] = token;
      }

      const response = await fetch(`${API_URL}/api/cart/items`, {
        method: "PUT",
        headers,
        body: JSON.stringify({ productId, quantity }),
      });

      if (response.ok) {
        const updatedCart = await response.json();
        setCart(updatedCart);
      } else {
        console.error("Failed to update quantity");
      }
    } catch (error) {
      console.error("Error updating quantity:", error);
    }
  };

  const removeFromCart = async (productId: number) => {
    const token = sessionToken || (typeof window !== "undefined" ? localStorage.getItem("sessionToken") : null);
    if (!user && !token) return;
    try {
      const tokenCookie = getCookie("token");
      const headers: HeadersInit = {};
      if (tokenCookie) {
        headers["Authorization"] = `Bearer ${tokenCookie}`;
      }
      if (!user && token) {
        headers["x-session-token"] = token;
      }

      const response = await fetch(`${API_URL}/api/cart/items/${productId}`, {
        method: "DELETE",
        headers,
      });

      if (response.ok) {
        const updatedCart = await response.json();
        setCart(updatedCart);
      } else {
        console.error("Failed to remove item");
      }
    } catch (error) {
      console.error("Error removing item:", error);
    }
  };

  const validateCouponOnServer = async (code: string, orderAmount: number) => {
    const response = await fetch(`${API_URL}/api/coupons/validate`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({ code, orderAmount })
    });

    if (!response.ok) {
      const errData = await response.json();
      throw new Error(errData.message || "Failed to validate coupon");
    }

    return response.json();
  };

  const clearCart = () => {
    setCart(null);
    if (typeof window !== "undefined") {
      localStorage.removeItem("sessionToken");
      setSessionToken(null);
    }
  };

  // Calculations
  const itemsCount = cart?.items?.reduce((sum, item) => sum + item.quantity, 0) || 0;
  const subtotal = cart?.items?.reduce((sum, item) => sum + item.quantity * item.unitPrice, 0) || 0;

  return (
    <CartContext.Provider
      value={{
        cart,
        itemsCount,
        subtotal,
        loading: loading || !isTokenLoaded,
        settings,
        isSidebarOpen,
        setSidebarOpen,
        addToCart,
        updateQuantity,
        removeFromCart,
        clearCart,
        refreshSettings: fetchSettings,
        validateCouponOnServer
      }}
    >
      {children}
    </CartContext.Provider>
  );
};

export const useCart = () => {
  const context = useContext(CartContext);
  if (context === undefined) {
    throw new Error("useCart must be used within a CartProvider");
  }
  return context;
};
